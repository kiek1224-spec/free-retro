import { writeFileSync } from "node:fs";
// Original NROM-128 test scene. A frame counter changes the background palette.
const code = [],
  labels = {},
  fix = [];
const emit = (...bytes) => code.push(...bytes);
const label = (n) => (labels[n] = code.length);
const abs = (op, n) => {
  emit(op, 0, 0);
  fix.push({ offset: code.length - 2, name: n, relative: false });
};
const branch = (op, n) => {
  emit(op, 0);
  fix.push({ offset: code.length - 1, name: n, relative: true });
};
label("reset");
emit(
  0x78,
  0xd8,
  0xa2,
  0xff,
  0x9a,
  0xe8,
  0x8e,
  0x00,
  0x20,
  0x8e,
  0x01,
  0x20,
  0x86,
  0x00,
);
label("vblank1");
emit(0x2c, 0x02, 0x20);
branch(0x10, "vblank1");
label("vblank2");
emit(0x2c, 0x02, 0x20);
branch(0x10, "vblank2");
emit(0xa9, 0x3f, 0x8d, 0x06, 0x20, 0xa9, 0x00, 0x8d, 0x06, 0x20, 0xa2, 0x00);
label("palette");
abs(0xbd, "colors");
emit(0x8d, 0x07, 0x20, 0xe8, 0xe0, 0x20);
branch(0xd0, "palette");
emit(
  0xa9,
  0x20,
  0x8d,
  0x06,
  0x20,
  0xa9,
  0x00,
  0x8d,
  0x06,
  0x20,
  0xa0,
  0x04,
  0xa2,
  0x00,
  0xa9,
  0x01,
);
label("fill");
emit(0x8d, 0x07, 0x20, 0xe8);
branch(0xd0, "fill");
emit(0x88);
branch(0xd0, "fill");
emit(
  0xa9,
  0x00,
  0x8d,
  0x05,
  0x20,
  0x8d,
  0x05,
  0x20,
  0xa9,
  0x80,
  0x8d,
  0x00,
  0x20,
  0xa9,
  0x0a,
  0x8d,
  0x01,
  0x20,
);
label("loop");
abs(0x4c, "loop");
label("nmi");
emit(
  0x48,
  0x8a,
  0x48,
  0x98,
  0x48,
  0xe6,
  0x00,
  0x2c,
  0x02,
  0x20,
  0xa9,
  0x3f,
  0x8d,
  0x06,
  0x20,
  0xa9,
  0x01,
  0x8d,
  0x06,
  0x20,
  0xa5,
  0x00,
  0x4a,
  0x4a,
  0x4a,
  0x29,
  0x0f,
  0x09,
  0x20,
  0x8d,
  0x07,
  0x20,
  0xa9,
  0x20,
  0x8d,
  0x06,
  0x20,
  0xa9,
  0,
  0x8d,
  0x06,
  0x20,
  0x8d,
  0x05,
  0x20,
  0x8d,
  0x05,
  0x20,
  0x68,
  0xa8,
  0x68,
  0xaa,
  0x68,
  0x40,
);
label("irq");
emit(0x40);
label("colors");
emit(
  ...Array.from({ length: 32 }, (_, i) =>
    i % 4 === 0 ? 0x0f : [0x0f, 0x21, 0x16, 0x30][i % 4],
  ),
);
for (const f of fix) {
  const target = 0x8000 + labels[f.name];
  if (f.relative) {
    const delta = labels[f.name] - (f.offset + 1);
    if (delta < -128 || delta > 127) throw new Error("branch range");
    code[f.offset] = delta & 255;
  } else {
    code[f.offset] = target & 255;
    code[f.offset + 1] = target >> 8;
  }
}
const prg = new Uint8Array(16384);
prg.fill(0xea);
prg.set(code);
for (const [n, at] of [
  ["nmi", 0x3ffa],
  ["reset", 0x3ffc],
  ["irq", 0x3ffe],
]) {
  prg[at] = (0x8000 + labels[n]) & 255;
  prg[at + 1] = (0x8000 + labels[n]) >> 8;
}
const chr = new Uint8Array(8192);
chr.set([0xaa, 0x55, 0xaa, 0x55, 0xaa, 0x55, 0xaa, 0x55], 16);
const rom = new Uint8Array(16 + prg.length + chr.length);
rom.set([0x4e, 0x45, 0x53, 0x1a, 1, 1, 0, 0]);
rom.set(prg, 16);
rom.set(chr, 16 + prg.length);
writeFileSync(new URL("runtime-fixture.nes", import.meta.url), rom);
console.log("Original test ROM generated:", rom.length, "bytes");
